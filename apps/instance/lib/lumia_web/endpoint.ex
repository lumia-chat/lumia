defmodule LumiaWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :lumia

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_lumia_key",
    signing_salt: "WdNFqAhI",
    same_site: "Lax"
  ]

  # The gateway (docs/protocol.md section 6). Bare protobuf or JSON frames;
  # the serializer maps them onto one Phoenix channel per socket. The
  # transport timeout is two missed 30-second heartbeats.
  # `auth_token` is a socket option (Phoenix copies it into the transport's
  # config and would overwrite one written inside `websocket:`).
  socket "/gateway", LumiaWeb.Gateway.Socket,
    auth_token: true,
    websocket: [
      serializer: [{LumiaWeb.Gateway.Serializer, "~> 1.0"}],
      timeout: 75_000,
      max_frame_size: 1_048_576
    ],
    longpoll: false

  # LiveView socket for the dev-only dashboard.
  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  # The web UI (apps/web), when a build is installed under priv/static/ui:
  # its hashed assets and the shared assets, with the SPA fallback in the
  # router (LumiaWeb.UiController). Not in the repo; see README.
  plug Plug.Static,
    at: "/",
    from: {:lumia, "priv/static/ui"},
    gzip: not code_reloading?,
    headers: %{"cache-control" => "public, max-age=31536000, immutable"},
    only_matching: ~w(assets brand fonts icons design)

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :lumia,
    gzip: not code_reloading?,
    only: LumiaWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :lumia
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]
  plug LumiaWeb.Plugs.Cors

  plug Plug.Parsers,
    parsers: [LumiaWeb.Plugs.ProtoBody, :urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug LumiaWeb.Router
end
