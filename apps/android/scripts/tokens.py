#!/usr/bin/env python3
"""Generates lumiakit/src/main/kotlin/chat/lumia/kit/Tokens.kt from
assets/design/tokens.json: every colour as a light/dark pair the composables
resolve per theme, the spacing, radii and sizes as dp, the type styles as
sizes and weights. Run by scripts/core.sh and by hand; the output is not
committed."""
import json, pathlib, re

root = pathlib.Path(__file__).resolve().parents[3]
tokens = json.loads((root / "assets/design/tokens.json").read_text())
out = pathlib.Path(__file__).resolve().parents[1] / "lumiakit/src/main/kotlin/chat/lumia/kit/Tokens.kt"

def ident(name):
    parts = name.split("-")
    s = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return {"class": "klass"}.get(s, s)

def argb(value):
    value = value.strip()
    if value.startswith("#"):
        h = value[1:]
        if len(h) == 3: h = "".join(c * 2 for c in h)
        return f"Color(0xFF{h.upper()})"
    m = re.match(r"rgba?\(([^)]*)\)", value)
    nums = [float(x) for x in m.group(1).split(",")]
    r, g, b = (int(n) for n in nums[:3]); a = nums[3] if len(nums) > 3 else 1
    return f"Color({r}, {g}, {b}, {int(round(a * 255))})"

def px(value):
    return float(value.replace("px", "")) if value.endswith("px") else None

lines = ["// Generated by scripts/tokens.py from assets/design/tokens.json; do not edit.",
         "package chat.lumia.kit", "",
         "import androidx.compose.ui.graphics.Color",
         "import androidx.compose.ui.unit.dp",
         "import androidx.compose.ui.unit.sp", "",
         "/** The design tokens (assets/design/tokens.json), by name. */",
         "object LumiaTokens {"]
lines.append("    // Colours (light and dark)")
for t in tokens["color"]["tokens"]:
    v = t["value"]
    if isinstance(v, dict):
        lines.append(f"    val {ident(t['name'])} = LumiaColor({argb(v['light'])}, {argb(v['dark'])})")
    else:
        lines.append(f"    val {ident(t['name'])} = LumiaColor({argb(v)}, {argb(v)})")
for group, name in (("spacing", "Spacing"), ("radius", "Radii"), ("size", "Sizes")):
    lines.append(f"    // {name} (dp)")
    for t in tokens[group]["tokens"]:
        p = px(t["value"])
        if p is None:
            if t["value"] == "50%": lines.append(f"    val {ident(t['name'])} = 999.dp // a circle")
            continue
        lines.append(f"    val {ident(t['name'])} = {p:g}.dp")
lines.append("    // Type styles")
for group in tokens["type"]["groups"]:
    display = group["family"] == "display"
    for s in group["styles"]:
        size = px(s["fontSize"]); weight = s.get("fontWeight", 400)
        lines.append(f"    val {ident(s['name'])} = LumiaType({size:g}.sp, {weight}, {'true' if display else 'false'})")
lines.append("}")
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines) + "\n")
print(f"{out.relative_to(root)}: {len(tokens['color']['tokens'])} colours")
