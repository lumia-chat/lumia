//! Turns the shared design assets into what the shell compiles in, as `apps/apple/scripts/tokens.py`
//! does for the Swift apps: `assets/design/tokens.json` becomes `tokens.rs` (every colour for
//! light and dark, the shadows, the spacing, radii and sizes as points, the type styles), the
//! WOFF2 fonts it lists become TrueType, which is what Rune reads, and `assets/icons` and the
//! brand symbol become `Icon`s. Nothing generated is committed.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use serde_json::Value;

fn main() {
    let assets =
        PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap_or_default()).join("../../assets");
    let out = PathBuf::from(env::var("OUT_DIR").unwrap_or_default());
    let tokens_path = assets.join("design/tokens.json");
    println!("cargo:rerun-if-changed={}", tokens_path.display());
    let tokens: Value =
        serde_json::from_str(&read(&tokens_path)).unwrap_or_else(|e| fail(&tokens_path, &e));

    let mut src =
        String::from("// Generated by build.rs from assets/design/tokens.json; do not edit.\n\n");
    colors(&tokens, &mut src);
    shadows(&tokens, &mut src);
    for group in ["spacing", "radius", "size"] {
        points(&tokens, group, &mut src);
    }
    type_styles(&tokens, &mut src);
    fonts(&tokens, &assets, &out, &mut src);
    icons(&assets, &mut src);
    write(&out.join("tokens.rs"), src.as_bytes());
}

fn read(path: &Path) -> String {
    fs::read_to_string(path).unwrap_or_else(|e| fail(path, &e))
}

fn write(path: &Path, bytes: &[u8]) {
    fs::write(path, bytes).unwrap_or_else(|e| fail(path, &e));
}

fn fail(path: &Path, why: &dyn std::fmt::Display) -> ! {
    panic!("{}: {why}", path.display())
}

fn list<'a>(tokens: &'a Value, group: &str, key: &str) -> &'a [Value] {
    tokens[group][key].as_array().map_or(&[], Vec::as_slice)
}

/// `hover-row` as `hover_row`, and as `HOVER_ROW` for a constant.
fn field(name: &str) -> String {
    name.replace('-', "_")
}

fn constant(name: &str) -> String {
    field(name).to_uppercase()
}

/// A CSS colour (`#rgb`, `#rrggbb`, `rgb()` or `rgba()`, all sRGB) as a Rune `Color`, which is
/// linear light with straight alpha.
fn color(value: &str) -> String {
    let value = value.trim();
    let (r, g, b, a) = if let Some(hex) = value.strip_prefix('#') {
        let hex: String = if hex.len() == 3 {
            hex.chars().flat_map(|c| [c, c]).collect()
        } else {
            hex.to_string()
        };
        let byte = |i: usize| {
            hex.get(i..i + 2)
                .and_then(|h| u8::from_str_radix(h, 16).ok())
                .map(f64::from)
        };
        match (byte(0), byte(2), byte(4)) {
            (Some(r), Some(g), Some(b)) => (r, g, b, 1.0),
            _ => panic!("tokens.json: not a colour: {value}"),
        }
    } else {
        let inner = value
            .trim_start_matches("rgba(")
            .trim_start_matches("rgb(")
            .trim_end_matches(')');
        let n: Vec<f64> = inner
            .split(',')
            .filter_map(|x| x.trim().parse().ok())
            .collect();
        match n.as_slice() {
            [r, g, b] => (*r, *g, *b, 1.0),
            [r, g, b, a] => (*r, *g, *b, *a),
            _ => panic!("tokens.json: not a colour: {value}"),
        }
    };
    let linear = |c: f64| {
        let c = c / 255.0;
        if c <= 0.04045 {
            c / 12.92
        } else {
            ((c + 0.055) / 1.055).powf(2.4)
        }
    };
    format!(
        "Color {{ r: {:.6}, g: {:.6}, b: {:.6}, a: {a:.4} }}",
        linear(r),
        linear(g),
        linear(b)
    )
}

fn colors(tokens: &Value, src: &mut String) {
    let all = list(tokens, "color", "tokens");
    src.push_str("/// Every colour token, resolved for one appearance.\n#[derive(Clone, Copy, Debug)]\npub struct Colors {\n");
    for t in all {
        let _ = writeln!(
            src,
            "    /// {}\n    pub {}: Color,",
            t["usage"].as_str().unwrap_or_default(),
            field(name(t))
        );
    }
    src.push_str("}\n\n");
    for theme in ["light", "dark"] {
        let _ = writeln!(
            src,
            "pub const {}: Colors = Colors {{",
            theme.to_uppercase()
        );
        for t in all {
            let value = match &t["value"] {
                Value::String(one) => one.as_str(),
                by_theme => by_theme[theme]
                    .as_str()
                    .unwrap_or_else(|| panic!("tokens.json: {} has no {theme} value", name(t))),
            };
            let _ = writeln!(src, "    {}: {},", field(name(t)), color(value));
        }
        src.push_str("};\n\n");
    }
}

fn name(token: &Value) -> &str {
    token["name"].as_str().unwrap_or_default()
}

fn px(value: &Value) -> Option<f64> {
    value.as_str()?.strip_suffix("px")?.parse().ok()
}

/// Spacing, radii and sizes, in points. `50%` (a circle) has no point value and is left out: a
/// view rounds by half its size.
fn points(tokens: &Value, group: &str, src: &mut String) {
    for t in list(tokens, group, "tokens") {
        if let Some(points) = px(&t["value"]) {
            let _ = writeln!(
                src,
                "/// {}\npub const {}: f32 = {points:?};",
                t["usage"].as_str().unwrap_or_default(),
                constant(name(t))
            );
        }
    }
    src.push('\n');
}

fn type_styles(tokens: &Value, src: &mut String) {
    for group in list(tokens, "type", "groups") {
        let display = group["family"] == "display";
        for s in group["styles"].as_array().map_or(&[][..], Vec::as_slice) {
            let size = px(&s["fontSize"]).unwrap_or(15.0);
            let weight = s["fontWeight"].as_f64().unwrap_or(400.0);
            let mut style = format!("TextStyle::new({size:?}, {weight:?})");
            if display {
                style.push_str(".family(DISPLAY)");
            }
            // Tracking is in em in the tokens and in points in Rune; a line height is a
            // multiple there and points here.
            if let Some(em) = s["letterSpacing"]
                .as_str()
                .and_then(|v| v.strip_suffix("em"))
                .and_then(|v| v.parse::<f64>().ok())
            {
                let _ = write!(
                    style,
                    ".tracking({:?})",
                    (em * size * 1000.0).round() / 1000.0
                );
            }
            if let Some(multiple) = s["lineHeight"].as_f64() {
                let _ = write!(style, ".lh({:?})", (multiple * size).round());
            }
            let _ = writeln!(
                src,
                "/// {}\npub const {}: TextStyle = {style};",
                s["usage"].as_str().unwrap_or_default(),
                constant(name(s))
            );
        }
    }
    src.push('\n');
}

/// The faces the tokens list, unpacked from WOFF2 beside the generated source.
fn fonts(tokens: &Value, assets: &Path, out: &Path, src: &mut String) {
    src.push_str("/// The faces `assets/design/tokens.json` lists, as TrueType.\npub const FONTS: &[&[u8]] = &[\n");
    for font in list(tokens, "type", "fonts") {
        let Some(file) = font["file"].as_str() else {
            continue;
        };
        let from = assets.join(file);
        println!("cargo:rerun-if-changed={}", from.display());
        let packed = fs::read(&from).unwrap_or_else(|e| fail(&from, &e));
        let unpacked = wuff::decompress_woff2(&packed)
            .unwrap_or_else(|e| panic!("{}: not WOFF2: {e:?}", from.display()));
        let name = Path::new(file).with_extension("ttf");
        let name = name
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or_default();
        write(&out.join(name), &unpacked);
        let _ = writeln!(
            src,
            "    include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{name}\")),"
        );
    }
    src.push_str("];\n");
}

/// A CSS `box-shadow` list as Rune `Shadow`s: `[inset] x y [blur [spread]] colour`, separated
/// by commas outside parentheses; `none` is no shadow.
fn shadow_list(value: &str) -> String {
    let mut layers = Vec::new();
    let mut depth = 0;
    let mut start = 0;
    for (i, ch) in value.char_indices() {
        match ch {
            '(' => depth += 1,
            ')' => depth -= 1,
            ',' if depth == 0 => {
                layers.push(&value[start..i]);
                start = i + 1;
            }
            _ => {}
        }
    }
    layers.push(&value[start..]);
    let mut out = String::from("&[");
    for layer in layers
        .iter()
        .map(|l| l.trim())
        .filter(|l| !l.is_empty() && *l != "none")
    {
        let inset = layer.starts_with("inset");
        let layer = layer.trim_start_matches("inset").trim();
        // The colour is the last term: a function with spaces inside, or one word.
        let (lengths, paint) = match layer.find("rgb") {
            Some(at) => layer.split_at(at),
            None => layer
                .rsplit_once(' ')
                .map_or((layer, ""), |(lengths, paint)| (lengths, paint)),
        };
        let n: Vec<f64> = lengths
            .split_whitespace()
            .filter_map(|l| l.trim_end_matches("px").parse().ok())
            .collect();
        let at = |i: usize| n.get(i).copied().unwrap_or(0.0);
        let _ = write!(
            out,
            "Shadow {{ x: {:?}, y: {:?}, blur: {:?}, spread: {:?}, color: {}, inset: {inset} }}, ",
            at(0),
            at(1),
            at(2),
            at(3),
            color(paint)
        );
    }
    out.push(']');
    out
}

fn shadows(tokens: &Value, src: &mut String) {
    let all = list(tokens, "shadow", "tokens");
    src.push_str("/// Every shadow token, resolved for one appearance: the layers of a CSS `box-shadow`.\n#[derive(Clone, Copy, Debug)]\npub struct Shadows {\n");
    for t in all {
        let _ = writeln!(
            src,
            "    /// {}\n    pub {}: &'static [Shadow],",
            t["usage"].as_str().unwrap_or_default(),
            field(name(t)).replace("shadow_", "")
        );
    }
    src.push_str("}\n\n");
    for theme in ["light", "dark"] {
        let _ = writeln!(
            src,
            "pub const {}_SHADOWS: Shadows = Shadows {{",
            theme.to_uppercase()
        );
        for t in all {
            let value = t["value"][theme].as_str().unwrap_or("none");
            let _ = writeln!(
                src,
                "    {}: {},",
                field(name(t)).replace("shadow_", ""),
                shadow_list(value)
            );
        }
        src.push_str("};\n\n");
    }
}

/// `name="value"` in an SVG tag.
fn attribute<'a>(tag: &'a str, name: &str) -> Option<&'a str> {
    let at = tag.find(&format!(" {name}=\""))? + name.len() + 3;
    tag[at..].split('"').next()
}

/// `assets/icons/*.svg` as Rune `Icon`s. The files carry their paint on the root element and a
/// fixed grey so they show as pictures; an `Icon` draws in its element's colour when its body
/// names none, so the paint moves to a group and the grey becomes `currentColor`.
fn icons(assets: &Path, src: &mut String) {
    let dir = assets.join("icons");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut files: Vec<PathBuf> = fs::read_dir(&dir)
        .unwrap_or_else(|e| fail(&dir, &e))
        .filter_map(|entry| entry.ok().map(|e| e.path()))
        .filter(|path| path.extension().is_some_and(|x| x == "svg"))
        .collect();
    files.sort();
    src.push_str("\n/// The stroke icons of `assets/icons`, each drawn in its element's colour.\npub mod icons {\n    use rune::Icon;\n\n");
    for path in files {
        let svg = read(&path);
        let stem = path
            .file_stem()
            .and_then(|s| s.to_str())
            .unwrap_or_default();
        let (Some(open_end), Some(close)) = (svg.find('>'), svg.rfind("</svg>")) else {
            fail(&path, &"not an SVG")
        };
        let (root, inner) = (&svg[..open_end], &svg[open_end + 1..close]);
        let mut group = String::from("<g");
        for paint in [
            "fill",
            "stroke",
            "stroke-width",
            "stroke-linecap",
            "stroke-linejoin",
        ] {
            if let Some(value) = attribute(root, paint) {
                let value = if value.starts_with('#') {
                    "currentColor"
                } else {
                    value
                };
                let _ = write!(group, " {paint}=\"{value}\"");
            }
        }
        let view = attribute(root, "viewBox")
            .and_then(|v| v.split_whitespace().nth(2)?.parse::<f64>().ok())
            .unwrap_or(24.0);
        let _ = writeln!(
            src,
            "    pub static {}: Icon = Icon {{ name: \"lumia-{stem}\", view: {view:?}, body: {:?} }};",
            constant(stem),
            format!("{group}>{inner}</g>")
        );
    }
    // The brand artwork keeps its own colours (gradients), so Rune draws it as full SVG.
    brand(
        assets,
        "lumia-original-icon",
        "LOGO",
        "The Lumia symbol",
        None,
        src,
    );
    // The stacked logo (the symbol over the wordmark) through the sign-in boards' window on
    // it, which trims the artwork's built-in clear space. The wordmark's ink is the file's,
    // so there is one for each appearance.
    for (file, name, ground) in [
        ("lumia-original-light", "LOGO_STACKED_LIGHT", "light"),
        ("lumia-original-dark", "LOGO_STACKED_DARK", "dark"),
    ] {
        brand(
            assets,
            file,
            name,
            &format!("The stacked Lumia logo for {ground} grounds, as the sign-in boards crop it"),
            Some(STACKED),
            src,
        );
    }
    let _ = writeln!(
        src,
        "    /// The stacked logo's size on the sign-in boards. No token names it: the numbers\n    /// are the boards' own (`build.rs`).\n    pub const LOGO_STACKED_WIDTH: f32 = {:?};\n    pub const LOGO_STACKED_HEIGHT: f32 = {:?};",
        STACKED.width, STACKED.height
    );
    src.push_str("}\n");
}

/// A window on a square piece of brand artwork, in the points a board draws it at.
#[derive(Clone, Copy)]
struct Window {
    /// The side the whole artwork is drawn at.
    drawn: f64,
    /// Where the window starts inside it, and its size.
    left: f64,
    top: f64,
    width: f64,
    height: f64,
}

/// How the sign-in boards show the stacked logo (`SignInLight.dc.html`, and `.auth__logo` in
/// `apps/web/src/app.css`): the artwork 246 points square, seen through a window 150 by 138
/// that starts 49 in and 57 down. The design system has no token for any of these.
const STACKED: Window = Window {
    drawn: 246.0,
    left: 49.0,
    top: 57.0,
    width: 150.0,
    height: 138.0,
};

/// `assets/brand/<file>.svg` as an `Icon` named `name`. An `Icon`'s view is a square from the
/// origin, which the artwork's view box need not be; `window` moves and narrows it to a part
/// of the artwork, the `Icon` being as wide as the window (what falls under the window's
/// height is the artwork's clear space).
fn brand(
    assets: &Path,
    file: &str,
    name: &str,
    doc: &str,
    window: Option<Window>,
    src: &mut String,
) {
    let path = assets.join(format!("brand/{file}.svg"));
    println!("cargo:rerun-if-changed={}", path.display());
    let svg = read(&path);
    let (Some(open), Some(close)) = (svg.find("<svg"), svg.rfind("</svg>")) else {
        fail(&path, &"not an SVG")
    };
    let open_end = open + svg[open..].find('>').unwrap_or(0);
    let view: Vec<f64> = attribute(&svg[open..open_end], "viewBox")
        .unwrap_or_default()
        .split_whitespace()
        .filter_map(|n| n.parse().ok())
        .collect();
    let [x, y, side, _] = view[..] else {
        fail(&path, &"no viewBox")
    };
    let (x, y, side) = match window {
        Some(w) => {
            // To a thousandth of the artwork's unit, which is all an `f32` view keeps.
            let unit = side / w.drawn;
            let round = |n: f64| (n * 1000.0).round() / 1000.0;
            (
                round(x + w.left * unit),
                round(y + w.top * unit),
                round(w.width * unit),
            )
        }
        None => (x, y, side),
    };
    let _ = writeln!(
        src,
        "    /// {doc} (`assets/brand`, all rights reserved; see its LICENSE).\n    pub static {name}: Icon = Icon {{ name: \"lumia-{}\", view: {side:?}, body: {:?} }};",
        name.to_lowercase().replace('_', "-"),
        format!(
            "<g transform=\"translate({} {})\">{}</g>",
            -x,
            -y,
            &svg[open_end + 1..close]
        )
    );
}
