#!/usr/bin/env python3
"""Generates LumiaKit/Sources/LumiaKit/Tokens.swift from assets/design/tokens.json:
every colour as a light/dark pair the views resolve per appearance, the
spacing, radii and sizes as points, the type styles as sizes and weights.
Run by scripts/core.sh and by hand; the output is not committed."""
import json, pathlib, re

root = pathlib.Path(__file__).resolve().parents[3]
tokens = json.loads((root / "assets/design/tokens.json").read_text())
out = pathlib.Path(__file__).resolve().parents[1] / "LumiaKit/Sources/LumiaKit/Tokens.swift"

def ident(name):
    parts = name.split("-")
    s = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return {"class": "klass"}.get(s, s)

def rgba(value):
    value = value.strip()
    if value.startswith("#"):
        h = value[1:]
        if len(h) == 3: h = "".join(c * 2 for c in h)
        r, g, b = (int(h[i:i+2], 16) / 255 for i in (0, 2, 4))
        return f"LumiaRGBA(r: {r:.4f}, g: {g:.4f}, b: {b:.4f}, a: 1)"
    m = re.match(r"rgba?\(([^)]*)\)", value)
    nums = [float(x) for x in m.group(1).split(",")]
    r, g, b = (n / 255 for n in nums[:3]); a = nums[3] if len(nums) > 3 else 1
    return f"LumiaRGBA(r: {r:.4f}, g: {g:.4f}, b: {b:.4f}, a: {a})"

def px(value):
    return float(value.replace("px", "")) if value.endswith("px") else None

lines = ["// Generated by scripts/tokens.py from assets/design/tokens.json; do not edit.",
         "import SwiftUI", "",
         "/// The design tokens (assets/design/tokens.json), by name.",
         "public enum LumiaTokens {"]
lines.append("    // MARK: Colours (light and dark)")
for t in tokens["color"]["tokens"]:
    v = t["value"]
    if isinstance(v, dict):
        lines.append(f"    public static let {ident(t['name'])} = LumiaColor(light: {rgba(v['light'])}, dark: {rgba(v['dark'])})")
    else:
        lines.append(f"    public static let {ident(t['name'])} = LumiaColor(light: {rgba(v)}, dark: {rgba(v)})")
for group, name in (("spacing", "Spacing"), ("radius", "Radii"), ("size", "Sizes")):
    lines.append(f"    // MARK: {name} (points)")
    for t in tokens[group]["tokens"]:
        p = px(t["value"])
        if p is None:
            if t["value"] == "50%": lines.append(f"    public static let {ident(t['name'])}: CGFloat = .infinity // a circle")
            continue
        lines.append(f"    public static let {ident(t['name'])}: CGFloat = {p:g}")
lines.append("    // MARK: Type styles")
for group in tokens["type"]["groups"]:
    display = group["family"] == "display"
    for s in group["styles"]:
        size = px(s["fontSize"]); weight = s.get("fontWeight", 400)
        lines.append(f"    public static let {ident(s['name'])} = LumiaType(size: {size:g}, weight: {weight}, display: {'true' if display else 'false'})")
lines.append("}")
out.write_text("\n".join(lines) + "\n")
print(f"{out.relative_to(root)}: {len(tokens['color']['tokens'])} colours")
