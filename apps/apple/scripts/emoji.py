#!/usr/bin/env python3
"""Writes LumiaKit/Sources/LumiaKit/EmojiData.swift, the emoji picker's list
(architecture 6.6), from the data the desktop shell's `emojis` crate carries
(Unicode's emoji list, fully qualified): every emoji in the default skin tone
up to Unicode 16 (the desktop found Unicode 18's drawn as boxes on this Mac),
with its group, name, shortcodes and Unicode version, by which the kit leaves
out what the running system cannot draw (`EmojiCatalog.newestDrawn`), one line
each in a string the kit reads at run time (a Swift array literal this long
takes the compiler minutes). Its output is committed.

    scripts/emoji.py <path to the emojis crate's src/gen/mod.rs>

`cargo metadata` in apps/desktop says where the crate is (emojis 0.9.1).
"""
import pathlib
import re
import sys

NEWEST = (16, 0)
GROUPS = {
    "SmileysAndEmotion": 0,
    "PeopleAndBody": 1,
    "AnimalsAndNature": 2,
    "FoodAndDrink": 3,
    "TravelAndPlaces": 4,
    "Activities": 5,
    "Objects": 6,
    "Symbols": 7,
    "Flags": 8,
}
# Emoji versions before 11 are not Unicode versions (UTS #51).
EARLY = {(0, 6): (6, 0), (0, 7): (7, 0), (1, 0): (8, 0), (2, 0): (8, 0), (3, 0): (9, 0), (4, 0): (9, 0), (5, 0): (10, 0), (13, 1): (13, 0)}

LINE = re.compile(
    r'Emoji \{ emoji: "(?P<emoji>[^"]+)", name: "(?P<name>[^"]+)", '
    r"emoji_version: EmojiVersion \{ major: (?P<major>\d+), minor: (?P<minor>\d+) \}, "
    r"group: Group::(?P<group>\w+), skin_tone: (?P<tone>None|Some\(\(\d+, \d+, SkinTone::(?P<which>\w+)\)\)), "
    r"shortcodes: (?P<codes>None|Some\(&\[[^\]]*\]\))"
)


def main() -> None:
    source = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
    rows = []
    for m in LINE.finditer(source):
        if m["tone"] != "None" and m["which"] != "Default":
            continue
        version = (int(m["major"]), int(m["minor"]))
        if EARLY.get(version, version) > NEWEST:
            continue
        codes = re.findall(r'"([^"]+)"', m["codes"]) if m["codes"] != "None" else []
        name = m["name"].replace("\t", " ")
        major, minor = EARLY.get(version, version)
        rows.append(f'{m["emoji"]}\t{GROUPS[m["group"]]}\t{name}\t{" ".join(codes)}\t{major}.{minor}')
    if len(rows) < 1500:
        sys.exit(f"only {len(rows)} emoji read; is that the emojis crate's gen/mod.rs?")
    body = "\n".join(rows).replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    out = pathlib.Path(__file__).resolve().parent.parent / "LumiaKit/Sources/LumiaKit/EmojiData.swift"
    out.write_text(
        "// Generated by scripts/emoji.py from the emojis crate's data (Unicode's\n"
        "// emoji list), default skin tone, up to Unicode 16. Do not edit.\n"
        "// One emoji a line: the emoji, its group (0 Smileys & emotion to 8 Flags),\n"
        "// its name, its shortcodes, the Unicode version it came in.\n\n"
        f'let emojiData = """\n{body}\n"""\n',
        encoding="utf-8",
    )
    print(f"{len(rows)} emoji to {out}")


main()
